const I18N_MISSING = new Set();
function t(ru, vars) {
  let s = ru;
  if (LANG !== 'ru') {
    const tr = I18N[ru];
    if (tr) s = tr[LANG === 'en' ? 0 : 1];
    else if (!I18N_MISSING.has(ru)) { I18N_MISSING.add(ru); console.warn('[i18n] нет перевода:', ru); }
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}
